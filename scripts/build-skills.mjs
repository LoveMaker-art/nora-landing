import {readFile,writeFile,mkdir,cp,rm} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import skills from '../skills/catalogue.js';
import {sources,packageUrls} from '../skills/sources.js';
const managerRoot='skill-library/nora-skill-library';
const skillText=await readFile(`${managerRoot}/SKILL.md`,'utf8');
const frontmatter=skillText.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)?.[1];
const managerVersion=frontmatter?.match(/^version: (\d+\.\d+\.\d+)$/m)?.[1];
if(!managerVersion)throw Error('Manager skill version is missing');
const managerPackage=`skills/packages/nora-skill-library-${managerVersion}.zip`;
await mkdir(`${managerRoot}/references`,{recursive:true});
await writeFile(`${managerRoot}/references/sources.json`,JSON.stringify(sources,null,2)+'\n');
await mkdir('skills/packages',{recursive:true});
execFileSync('python3',['-c',`
from pathlib import Path
import zipfile,sys
root=Path('skill-library/nora-skill-library')
with zipfile.ZipFile(sys.argv[1],'w',zipfile.ZIP_DEFLATED) as z:
 for p in sorted(root.rglob('*')):
  if p.is_file() and '__pycache__' not in p.parts and p.name!='.DS_Store':
   info=zipfile.ZipInfo('nora-skill-library/'+p.relative_to(root).as_posix(),(2026,10,23,0,0,0))
   info.external_attr=0o100644<<16
   info.compress_type=zipfile.ZIP_DEFLATED
   z.writestr(info,p.read_bytes())
`,managerPackage]);
const bytes=await readFile(managerPackage);
const manager={id:'nora-skill-library',title:'诺拉技能库管理',version:managerVersion,package:`packages/nora-skill-library-${managerVersion}.zip`,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};
await writeFile('skills/manager.js','// Generated by scripts/build-skills.mjs\nexport default '+JSON.stringify(manager,null,2)+';\n');
await rm('skills/guides/nora-skill-library',{recursive:true,force:true});
await cp(managerRoot,'skills/guides/nora-skill-library',{recursive:true,filter:p=>!p.includes('__pycache__')});
const data={schema_version:1,library:sources.library,release_state:'published',catalogue_urls:sources.catalogueUrls,skills:skills.map(s=>({id:s.id,title:s.title,description:s.description,delivery:s.delivery,requirement:s.requirement,...(s.delivery==='download'?{version:s.version,package:{filename:s.package.split('/').pop(),root_directory:s.id,bytes:s.bytes,sha256:s.sha256,urls:packageUrls(s)}}:{})}))};
await writeFile('skills/catalogue.json',JSON.stringify(data,null,2)+'\n');
const local=JSON.parse(JSON.stringify(data));local.release_state='local-test';
local.catalogue_urls=['http://127.0.0.1:8776/skills/catalogue.local.json'];
for(const item of local.skills)if(item.package)item.package.urls=['http://127.0.0.1:8776/skills/packages/'+item.package.filename];
await writeFile('skills/catalogue.local.json',JSON.stringify(local,null,2)+'\n');
